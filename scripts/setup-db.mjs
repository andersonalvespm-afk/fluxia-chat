import { readFileSync } from "node:fs";
import { Client } from "pg";

// ---- lê o .env manualmente (sem depender de dotenv) ----
function loadEnv(path = ".env") {
  const out = {};
  const raw = readFileSync(path, "utf8");
  for (const line of raw.split(/\r?\n/)) {
    const m = line.match(/^\s*([\w.]+)\s*=\s*(.*)\s*$/);
    if (!m) continue;
    let val = m[2].trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    out[m[1]] = val;
  }
  return out;
}

const env = loadEnv();

// Host do pooler do Supabase (Session pooler / Supavisor).
// Região é extraída da URL do projeto; ajuste SUPABASE_DB_HOST se necessário.
const projectRef = new URL(env.NEXT_PUBLIC_SUPABASE_URL).hostname.split(".")[0];

const SQL = `
create table if not exists public.messages (
  id          bigint generated by default as identity primary key,
  role        text not null check (role in ('user', 'assistant')),
  content     text not null,
  created_at  timestamptz not null default now()
);

create index if not exists messages_created_at_idx
  on public.messages (created_at desc);

alter table public.messages enable row level security;

drop policy if exists "messages_public_read" on public.messages;
create policy "messages_public_read"
  on public.messages
  for select
  using (true);
`;

async function main() {
  const client = new Client({
    host: process.env.SUPABASE_DB_HOST || "aws-0-us-east-1.pooler.supabase.com",
    port: Number(process.env.SUPABASE_DB_PORT || 5432),
    user: `postgres.${projectRef}`,
    password: env.DATABASE_PASSWORD,
    database: "postgres",
    ssl: { rejectUnauthorized: false },
    connectionTimeoutMillis: 15000,
  });

  console.log(`Conectando em ${client.host} como postgres.${projectRef} ...`);
  await client.connect();
  console.log("✅ Conectado!");

  await client.query(SQL);
  console.log("✅ Schema aplicado (tabela 'messages' + RLS + policy).");

  const res = await client.query(
    "select column_name, data_type from information_schema.columns where table_name='messages' order by ordinal_position;"
  );
  console.table(res.rows);

  await client.end();
}

main().catch((err) => {
  console.error("❌ Falha:", err.message);
  process.exit(1);
});
