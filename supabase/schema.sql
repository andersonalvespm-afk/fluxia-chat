-- Tabela de mensagens
create table if not exists public.messages (
  id          bigint generated by default as identity primary key,
  role        text not null check (role in ('user', 'assistant')),
  content     text not null,
  created_at  timestamptz not null default now()
);

-- Índice para listar conversas por data
create index if not exists messages_created_at_idx
  on public.messages (created_at desc);

-- ------------------------------------------------------------
-- Segurança em nível de linha (RLS)
-- ------------------------------------------------------------
alter table public.messages enable row level security;

-- Permitir que qualquer visitante LEIA as mensagens (ajuste conforme seu caso)
drop policy if exists "messages_public_read" on public.messages;
create policy "messages_public_read"
  on public.messages
  for select
  using (true);

-- Inserção é feita apenas pelo servidor (service_role), que ignora RLS.
-- Por isso não criamos policy de INSERT para o público.
